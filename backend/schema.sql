CREATE TABLE IF NOT EXISTS events (
 id SERIAL PRIMARY KEY, title VARCHAR(180) NOT NULL, description TEXT NOT NULL DEFAULT '', category VARCHAR(60) NOT NULL DEFAULT 'Community',
 venue VARCHAR(180) NOT NULL, city VARCHAR(100) NOT NULL DEFAULT 'Hyderabad', starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL,
 capacity INTEGER NOT NULL DEFAULT 100 CHECK(capacity > 0), price NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK(price >= 0), organizer VARCHAR(120) NOT NULL DEFAULT 'Event Team',
 status VARCHAR(20) NOT NULL DEFAULT 'published' CHECK(status IN ('published','cancelled')), created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS registrations (
 id SERIAL PRIMARY KEY, event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE, attendee_name VARCHAR(120) NOT NULL,
 attendee_email VARCHAR(180) NOT NULL, ticket_type VARCHAR(40) NOT NULL DEFAULT 'General', quantity INTEGER NOT NULL DEFAULT 1 CHECK(quantity BETWEEN 1 AND 10),
 confirmation_code VARCHAR(24) NOT NULL UNIQUE, registered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(event_id, attendee_email)
);
CREATE TABLE IF NOT EXISTS agenda_items (
 id SERIAL PRIMARY KEY, event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE, title VARCHAR(180) NOT NULL,
 speaker VARCHAR(120) NOT NULL DEFAULT '', starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL, details TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS notifications (
 id SERIAL PRIMARY KEY, event_id INTEGER REFERENCES events(id) ON DELETE CASCADE, title VARCHAR(180) NOT NULL, message TEXT NOT NULL,
 kind VARCHAR(30) NOT NULL DEFAULT 'info', is_read BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_events_starts_at ON events(starts_at);
CREATE INDEX IF NOT EXISTS idx_registrations_event_id ON registrations(event_id);
